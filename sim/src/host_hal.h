// OpenTracker simulator -- small HAL pieces: clock, input queue, pad LEDs.
#pragma once

#include <array>
#include <chrono>
#include <cstdint>
#include <deque>
#include <mutex>

#include "hal_api.h"

namespace sim {

// Real time (std::chrono steady clock since start) or a virtual clock the
// headless script advances explicitly.
class SimClock final : public ot::IClock {
public:
    SimClock() : t0_(std::chrono::steady_clock::now()) {}
    void setVirtual(bool v) { virtual_ = v; }
    bool isVirtual() const { return virtual_; }
    void advanceUs(uint64_t us) { vus_ += us; }
    uint64_t nowUs() const {
        if (virtual_) return vus_;
        return uint64_t(std::chrono::duration_cast<std::chrono::microseconds>(
                            std::chrono::steady_clock::now() - t0_).count());
    }
    uint32_t micros() const override { return uint32_t(nowUs()); }
    uint32_t millis() const override { return uint32_t(nowUs() / 1000); }

private:
    std::chrono::steady_clock::time_point t0_;
    bool virtual_ = false;
    uint64_t vus_ = 0;
};

// Event queue fed by the SDL front end or the script. Mirrors the device
// driver: buttons in the auto-repeat group (spec 05 §2.1.1) re-send presses
// while held with the 333 ms / accel table timing; hold ticks of the other
// buttons are generated by the app itself.
class SimInput final : public ot::IInput {
public:
    explicit SimInput(const ot::IClock& clk) : clk_(clk) {}
    bool poll(ot::InputEvent& ev) override;
    void button(uint8_t id, bool down);
    void pad(uint8_t pad, bool down, uint8_t velocity = 100);
    void encoder(int delta);
    bool buttonDown(uint8_t id) const { return id < 64 && (buttons_ >> id) & 1; }
    bool padDown(uint8_t p) const { return p < 64 && (pads_ >> p) & 1; }
    void service();   // auto-repeat timing; poll() calls it too

private:
    void push(ot::InputEvent::Type t, uint8_t id, uint8_t vel = 0, int8_t d = 0);
    const ot::IClock& clk_;
    std::mutex mu_;
    std::deque<ot::InputEvent> q_;
    uint64_t buttons_ = 0, pads_ = 0;
    uint32_t holdNext_[64] = {};
    uint8_t holdLevel_[64] = {};
};

class SimLeds final : public ot::ILeds {
public:
    static constexpr int kPads = 48;
    uint8_t padCount() const override { return kPads; }
    void setPad(uint8_t pad, uint8_t r, uint8_t g, uint8_t b) override {
        if (pad < kPads) pending_[pad] = (uint32_t(r) << 16) | (uint32_t(g) << 8) | b;
    }
    void clear() override { pending_.fill(0); }
    void show() override {
        std::lock_guard<std::mutex> lk(mu_);
        shown_ = pending_;
    }
    uint32_t color(int pad) const {
        std::lock_guard<std::mutex> lk(mu_);
        return pad >= 0 && pad < kPads ? shown_[pad] : 0;
    }

private:
    std::array<uint32_t, kPads> pending_{}, shown_{};
    mutable std::mutex mu_;
};

}  // namespace sim
